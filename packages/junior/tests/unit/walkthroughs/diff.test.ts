describe("parsePatch", () => {
  it("reads hunk ranges and line numbers on both sides", () => {
    const hunks = parsePatch(boardPatch);
    expect(hunks.map(({ head, base }) => ({ head, base }))).toEqual([
      { base: { start: 12, end: 17 }, head: { start: 12, end: 18 } },
      { base: { start: 114, end: 122 }, head: { start: 115, end: 122 } },
    ]);
    expect(hunks[0]?.lines[3]).toEqual({
      kind: "add",
      content:
        'import { listedConversation } from "@/chat/conversations/sql/listed";',
      newLine: 15,
    });
    expect(hunks[1]?.lines.filter((line) => line.kind === "remove")).toEqual([
      {
        kind: "remove",
        content: "        isNull(juniorConversations.parentConversationId),",
        oldLine: 117,
      },
      {
        kind: "remove",
        content: "        isNull(juniorConversations.quickQuestionAt),",
        oldLine: 119,
      },
    ]);
  });

  it("gives a new file no base side and a deleted file no head side", () => {
    const [added] = parsePatch("@@ -0,0 +1,2 @@\n+a\n+b");
    expect(added?.head).toEqual({ start: 1, end: 2 });
    expect(added).not.toHaveProperty("base");
    const [removed] = parsePatch(
      "@@ -1 +0,0 @@\n-a\n\\ No newline at end of file",
    );
    expect(removed?.base).toEqual({ start: 1, end: 1 });
    expect(removed).not.toHaveProperty("head");
    expect(removed?.lines).toHaveLength(1);
  });
});

describe("readWalkthroughDiff", () => {
  it("keeps code and counts mechanical files per reason", () => {
    const diff = readWalkthroughDiff(3071, [
      {
        path: "packages/junior/src/api/board/read.ts",
        status: "modified",
        patch: boardPatch,
      },
      {
        path: "pnpm-lock.yaml",
        status: "modified",
        patch: "@@ -1 +1 @@\n-a\n+b",
      },
      {
        path: "packages/x/dist/index.js",
        status: "modified",
        patch: "@@ -1 +1 @@\n-a\n+b",
      },
      {
        path: "src/schema.ts",
        status: "added",
        patch: "@@ -0,0 +1,2 @@\n+// @generated by a tool\n+x",
      },
      {
        path: "src/new-name.ts",
        previousPath: "src/old-name.ts",
        status: "renamed",
      },
      { path: "assets/logo.png", status: "modified" },
      {
        path: "src/format.ts",
        status: "modified",
        patch: "@@ -1,2 +1,2 @@\n-if(a){b()}\n+if (a) { b() }\n context",
      },
    ]);
    expect(diff.files.map((file) => file.path)).toEqual([
      "packages/junior/src/api/board/read.ts",
    ]);
    expect(diff.skipped).toEqual([
      { reason: "lockfile", files: 1, lines: 2 },
      { reason: "generated", files: 2, lines: 4 },
      { reason: "rename", files: 1, lines: 0 },
      { reason: "no_diff", files: 1, lines: 0 },
      { reason: "whitespace", files: 1, lines: 2 },
    ]);
  });
});

describe("buildWalkthroughExcerpts", () => {
  const { files } = readWalkthroughDiff(3071, [
    { path: "src/read.ts", status: "modified", patch: boardPatch },
  ]);

  it("copies the cited lines with the removed lines between them", () => {
    const [excerpt] = buildWalkthroughExcerpts(
      [{ pr: 3071, path: "src/read.ts", side: "head", start: 117, end: 119 }],
      files,
      new Map(),
    );
    expect(excerpt?.id).toBe("3071:head:src/read.ts#117-119");
    expect(excerpt?.lines.map((line) => line.kind)).toEqual([
      "context",
      "remove",
      "add",
      "context",
    ]);
  });

  it("copies head-side lines outside the diff from the file text", () => {
    const [excerpt] = buildWalkthroughExcerpts(
      [{ pr: 3071, path: "src/caller.ts", side: "head", start: 2, end: 3 }],
      files,
      new Map([["3071:src/caller.ts", "one\ntwo\nthree\n"]]),
    );
    expect(excerpt?.lines).toEqual([
      { kind: "context", content: "two", newLine: 2 },
      { kind: "context", content: "three", newLine: 3 },
    ]);
  });
});
