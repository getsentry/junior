import { writeFile } from "node:fs/promises";
import octicons from "@primer/octicons";
import { chromium } from "@playwright/test";

// The web uses the original 16px Octicons paths. Slack uses a 64px PNG of
// the same paths on a neutral tile that remains readable in either theme.
const names = [
  "issue-opened",
  "issue-closed",
  "git-pull-request",
  "git-pull-request-draft",
  "git-pull-request-closed",
  "git-merge",
  "workflow",
  "rocket",
  "package",
];
const paths = Object.fromEntries(
  names.map((name) => [
    name,
    octicons[name].heights[16].ast.children.map((node) => node.attributes.d),
  ]),
);
await writeFile(
  "packages/junior-plugin-api/src/object-icons.ts",
  `// Generated by scripts/generate-object-icons.mjs. Do not edit.\n// Octicons copyright GitHub, Inc. MIT license: see object-icons.LICENSE.\nimport type { ObjectIconName } from "./object-presentation";\n\n/** Original Octicons paths, shared by web and Slack image assets. */\nexport const objectIconPaths = ${JSON.stringify(paths, null, 2)} satisfies Record<ObjectIconName, string[]>;\n`,
);
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({
    viewport: { width: 64, height: 64 },
    deviceScaleFactor: 1,
  });
  const images = {};
  for (const name of names) {
    await page.setContent(
      `<style>body{margin:0;background:#f6f8fa;display:grid;place-items:center;width:64px;height:64px}</style><svg width="40" height="40" viewBox="0 0 16 16" fill="#24292f">${octicons[name].heights[16].path}</svg>`,
    );
    images[name] = (await page.screenshot()).toString("base64");
  }
  await writeFile(
    "packages/junior-dashboard/src/object-icon-images.ts",
    `// Generated by scripts/generate-object-icons.mjs. Do not edit.\n// Octicons copyright GitHub, Inc. MIT license: see ../../junior-plugin-api/src/object-icons.LICENSE.\n\n/** PNG assets for Slack clients, which do not render inline SVG. */\nexport const objectIconImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`,
  );
} finally {
  await browser.close();
}
