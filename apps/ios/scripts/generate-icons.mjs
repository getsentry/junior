// Write Junior/Theme/IconPaths.swift from the dashboard's own icon sources:
// the Lucide icons it imports, the Octicons in junior-plugin-api, and the
// Slack and GitHub marks. Run after those sources change or when the app
// needs another icon: `node apps/ios/scripts/generate-icons.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../..",
);
const read = (file) => readFileSync(path.join(root, file), "utf8");

const octicons = read("packages/junior-plugin-api/src/object-icons.ts");
const icons = {};
for (const match of octicons.matchAll(
  /"?([\w-]+)"?: \[\s*((?:"[^"]*",?\s*)+)\]/g,
)) {
  icons[match[1]] = [...match[2].matchAll(/"([^"]*)"/g)].map((m) => m[1]);
}

const marks = {};
for (const [name, file] of [
  ["slack", "packages/junior-dashboard/src/client/conversations/SlackMark.tsx"],
  [
    "github",
    "packages/junior-dashboard/src/client/conversations/GitHubMark.tsx",
  ],
]) {
  const source = read(file);
  const [, w, h] = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(source);
  marks[name] = {
    size: Number(w),
    paths: [...source.matchAll(/ d="([^"]*)"/g)].map((m) => m[1]),
  };
  if (Number(h) !== Number(w)) throw new Error(`${name} mark is not square`);
}

